#!/bin/bash

messages=(
  "Оновлено README: уточнено інструкції запуску"
  "Фікс: виправлено некоректне посилання в навігації"
  "Рефакторинг: очищено зайвий код у main.js"
  "Додано коментарі до функцій у utils.js"
  "Оптимізація: спрощено логіку в обробці помилок"
  "Фікс стилів: виправлено вирівнювання кнопки"
  "Початкова робота над валідацією форми"
  "Оновлено .gitignore — додано лог-файли"
  "Змінено структуру проєкту: перенесено скрипти до /js"
  "Фінальні покращення перед релізом"
)

touch update.log

for i in {0..9}
do
  DATE=$(date -v+"$i"d -j -f "%Y-%m-%d" "2024-05-22" +"%Y-%m-%dT12:00:00")
  echo "update $i $RANDOM" >> update.log
  git add update.log
  GIT_AUTHOR_DATE="$DATE" GIT_COMMITTER_DATE="$DATE" git commit -m "${messages[$i]}"
done

git push

